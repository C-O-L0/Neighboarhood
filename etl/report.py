"""Write docs/import_report.md from the cleaner's clean_report.json.

The report records what the import did to the pinned snapshot: rows in and out
per table, rows rejected and why, every cleaning rule with its count, and the
geocoding match rate. It is committed, so regenerate it after any change to the
cleaner or the geocode cache:

    python -m etl.clean
    python -m etl.report [--interim data/interim] [--out docs/import_report.md]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

from etl import db_counts as dbc
from etl.download import load_manifest

TABLE_SOURCE = {
    "town": "fixed list in etl/clean.py (27 property town codes)",
    "flat_type": "fixed list (7 resale types + STUDIO APARTMENT, OTHER)",
    "flat_model": "fixed list (21 models in the snapshot)",
    "building": "property dataset + stub blocks with sales but no property row",
    "building_flat_supply": "property dataset supply columns, all-zero pairs skipped",
    "resale_transaction": "resale dataset, one row per sale",
    "hawker_centre": "hawker GeoJSON, one row per feature",
}


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "n/a"


def _sales(n: int) -> str:
    return f"{n} sale{'s' if n != 1 else ''}"


def _lease_treatment(a: dict, tol: int) -> str:
    """Treatment cell for a block whose sales disagree on the lease commencement year."""
    values = {int(y): n for y, n in a["values"].items()}  # keys are strings after a JSON round trip
    evidence = {int(y): e for y, e in a["evidence"].items()}
    chosen, total = int(a["chosen"]), sum(values.values())
    vals = ", ".join(f"{y} ({_sales(n)})" for y, n in values.items())
    if a["method"] == "majority_fallback":
        return (
            f"values {vals}; no value matches any sale's remaining lease within {tol} months, "
            f"so the majority value {chosen} is stored on `building`"
        )
    others = [y for y in values if y != chosen]
    fits = evidence[chosen]["consistent_sales"]
    if fits == total:
        matched = f"the remaining lease of every sale, including the {_sales(sum(values[y] for y in others))} "
        matched += f"recorded as {' or '.join(map(str, others))}, matches {chosen} within {tol} months"
    else:
        matched = f"{chosen} matches the remaining lease of {fits} of {total} sales within {tol} months"
    rest = "; ".join(f"{y} matches {_sales(evidence[y]['consistent_sales'])}" for y in others)
    return f"values {vals}; {chosen} stored on `building`, chosen by remaining lease: {matched}; {rest}"


def _db_counts_section(report: dict, db_counts: dict) -> tuple[list[str], bool]:
    """Lines for the "Database counts" section, and whether the counts match this cleaning run."""
    if db_counts["rows_out"] != report["rows_out"]:
        return [
            "## Database counts",
            "",
            "The database counts are stale: they were taken for a different cleaning run. "
            "Reload both databases and rerun `python -m etl.db_counts`, then regenerate this report.",
            "",
        ], False
    lines = [
        "## Database counts",
        "",
        "| Entity | Cleaning output | PostgreSQL | MongoDB | Match |",
        "|---|---:|---:|---:|---|",
    ]
    for r in dbc.compare(db_counts["entities"], report):
        cells = (dbc.cell(r["mode"], side, r[side]) for side in ("cleaning", "pg", "mongo"))
        lines.append(f"| {r['label']} | " + " | ".join(cells) + f" | {'yes' if r['match'] else 'no'} |")
    lines += [
        "",
        f"Counts were taken from the loaded databases at {db_counts['taken_at']} by `etl/db_counts.py`. "
        "Match compares only the pairs that exist: lookup tables are checked against cleaning in PostgreSQL "
        "(MongoDB embeds them), and sales and buyer figures with no cleaning counterpart are checked between "
        "the two databases.",
        "",
    ]
    return lines, True


def render(report: dict, rejected: pd.DataFrame | None = None, db_counts: dict | None = None) -> str:
    m = load_manifest()
    rows_in, rows_out = report["rows_in"], report["rows_out"]
    section, fresh = _db_counts_section(report, db_counts) if db_counts else ([], False)
    out: list[str] = []
    w = out.append

    w("# Import report")
    w("")
    w(f"Generated by `etl/report.py` from `clean_report.json`. Source snapshot: **{m['snapshot']}** ")
    w(f"(retrieved {m['retrieved']}, SHA-256 pinned in `etl/manifest.json`). Input folder: `{report['raw_dir']}`.")
    w("")
    if fresh:
        w(
            "Other counts in this report are cleaning output (rows written to `data/interim/*.parquet`). "
            'Counts taken from PostgreSQL and MongoDB after loading are in "Database counts".'
        )
    else:
        w(
            "All counts below are cleaning output (rows written to `data/interim/*.parquet`), not database counts. "
            "Loading is a separate step (`etl/load_pg.py`, `etl/load_mongo.py`) and its counts are not in this report."
        )
    w("")

    w("## Source files")
    w("")
    w("| File | Publisher | Rows read | Rows in manifest |")
    w("|---|---|---:|---:|")
    keys = {"Resale": "resale", "HDBProperty": "property", "Hawker": "hawker"}
    for f in m["files"]:
        k = next(v for p, v in keys.items() if f["name"].startswith(p))
        w(f"| `{f['name']}` | {f['publisher']} | {rows_in[k]:,} | {f['rows']:,} |")
    w("")

    w("## Tables produced")
    w("")
    w("| Table | Rows | Built from |")
    w("|---|---:|---|")
    for t, n in rows_out.items():
        w(f"| `{t}` | {n:,} | {TABLE_SOURCE.get(t, '')} |")
    w("")
    sales_in, sales_out = rows_in["resale"], rows_out["resale_transaction"]
    w(
        f"Sales: {sales_in:,} read, {sales_out:,} accepted by cleaning, {report['rejected']:,} rejected. "
        f"Blocks: {rows_in['property']:,} in the property dataset, {rows_out['building']:,} buildings "
        f"({len(report['stub_buildings'])} stub)."
    )
    w("")
    out.extend(section)

    w("## Rejected rows")
    w("")
    if report["rejected"] == 0:
        w("None. Every sale passed the type and range checks that mirror the PostgreSQL CHECK constraints.")
    else:
        w(f"{report['rejected']:,} rows, listed in `data/interim/rejected_rows.csv`. By reason:")
        w("")
        if rejected is not None and len(rejected):
            reasons = rejected["reason"].str.replace(r"'.*'", "'...'", regex=True).value_counts()
            w("| Reason | Rows |")
            w("|---|---:|")
            for reason, n in reasons.items():
                w(f"| {reason} | {n:,} |")
    w("")

    w("## Cleaning rules applied")
    w("")
    w("| Rule | Count | Treatment |")
    w("|---|---:|---|")
    dup = report["duplicates_kept"]
    w(f"| Exact duplicate sale rows | {dup:,} | kept as separate sales (no unit number to tell them apart) |")
    w(
        f"| Fractional resale prices | {report['fractional_prices']:,} | stored exactly as NUMERIC(9,2) / Decimal128, "
        "never as integer or float |"
    )
    for s in report["stub_buildings"]:
        w(
            f"| Block with sales but no property row: {s['block']} {s['street']} ({s['town'].title()}) | "
            f"{s['sales']} sales | kept as a stub building (`in_property_dataset = false`, attributes null) |"
        )
    tol = report["lease_remaining_tolerance_months"]
    for a in report["lease_year_anomalies"]:
        w(
            f"| Block with two lease commencement years: {a['block']} {a['street']} | 1 block | "
            f"{_lease_treatment(a, tol)} |"
        )
    w(
        f"| Sale whose remaining lease disagrees with its own lease commencement year | "
        f"{report['lease_remaining_inconsistent']:,} | more than {tol} months from a 99-year lease starting that "
        "year; reported only, the sale is kept |"
    )
    w(
        f"| All-zero supply pairs (block, flat type) | {report['supply_zero_pairs_skipped']:,} | skipped; "
        "per-block supply still sums to `total_dwelling_units` for every block |"
    )
    w(
        f"| Town code disagreeing with resale town | {report['town_code_mismatches']:,} | "
        "checked for every resold block |"
    )
    w(
        f"| Sale dated before block completion year | {report['sales_before_completion']:,} | "
        "checked; the same rule is a PostgreSQL trigger for new sales |"
    )
    w("")
    w("Remaining-lease formats parsed into `remaining_lease_months`:")
    w("")
    w("| Format | Example | Rows |")
    w("|---|---|---:|")
    examples = {
        "years and months": "61 years 04 months",
        "years and 1 month": "61 years 01 month",
        "years only": "95 years",
    }
    for fmt, n in sorted(report["remaining_lease_formats"].items(), key=lambda kv: -kv[1]):
        w(f"| {fmt} | `{examples.get(fmt, '')}` | {n:,} |")
    w("")

    w("## Geocoding")
    w("")
    c = report["coordinates"]
    if not c["cache_present"]:
        w("No geocode cache was present when this report was generated, so building coordinates are null.")
    else:
        got, need = c["target_buildings_geocoded"], c["target_buildings"]
        w(
            f"Target blocks (residential or resold): {need:,}. With coordinates: {got:,} ({_pct(got, need)}). "
            f"Manual overrides: {c['overrides']:,}."
        )
        w("")
        w("OneMap match status in `data/cache/block_coordinates.csv`:")
        w("")
        w("| Status | Blocks |")
        w("|---|---:|")
        for status, n in sorted(c.get("cache_status", {}).items(), key=lambda kv: -kv[1]):
            w(f"| {status} | {n:,} |")
    w("")

    w("## Hawker centres")
    w("")
    w("| Status | Centres |")
    w("|---|---:|")
    for status, n in report["hawker_status"].items():
        w(f"| {status} | {n:,} |")
    w("")
    w("Food-access queries exclude `Under Construction` in both databases.")
    w("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--interim", type=Path, default=Path("data/interim"))
    ap.add_argument("--out", type=Path, default=Path("docs/import_report.md"))
    ap.add_argument("--db-counts", type=Path, default=None, help="db_counts.json (default: <interim>/db_counts.json)")
    args = ap.parse_args(argv)

    report = json.loads((args.interim / "clean_report.json").read_text(encoding="utf-8"))
    rej_path = args.interim / "rejected_rows.csv"
    rejected = pd.read_csv(rej_path) if rej_path.exists() else None
    counts_path = args.db_counts or args.interim / "db_counts.json"
    db_counts = json.loads(counts_path.read_text(encoding="utf-8")) if counts_path.exists() else None
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(report, rejected, db_counts), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
