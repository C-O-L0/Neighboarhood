-- Households (UC10): two accounts share one shortlist of at most 50 blocks.
--
-- household             one row per household
-- household_member      M:1 buyer to household. The buyer is the key, so an account is in at most one
--                       household; a seat of 1 or 2, unique per household, caps it at two members.
-- household_invitation  a pending invitation. The inviter is the key: one outstanding invitation each.
-- household_saved       M:N between household and building: the shared shortlist, with who saved each
--                       block and who wrote its note.
--
-- A member's shortlist is the household's, so a member has no personal rows in saved_building: accepting
-- an invitation moves them (app/repos/pg/households.py), and trigger (d) refuses new ones.

CREATE TABLE household (
    household_id  INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
COMMENT ON TABLE household IS 'Two accounts sharing one shortlist (UC10).';

CREATE TABLE household_member (
    buyer_id      INT          PRIMARY KEY REFERENCES buyer ON DELETE CASCADE,
    household_id  INT          NOT NULL REFERENCES household ON DELETE CASCADE,
    seat          SMALLINT     NOT NULL CHECK (seat IN (1, 2)),
    joined_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (household_id, seat)
);
COMMENT ON TABLE household_member IS 'One household per buyer (primary key); at most 2 per household (seat 1 or 2, unique).';

CREATE TABLE household_invitation (
    inviter_id  INT          PRIMARY KEY REFERENCES buyer ON DELETE CASCADE,
    invitee_id  INT          NOT NULL REFERENCES buyer ON DELETE CASCADE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (invitee_id <> inviter_id)
);
COMMENT ON TABLE household_invitation IS 'A pending invitation; one per inviter. Accepting or declining deletes it.';

CREATE TABLE household_saved (
    household_id  INT           NOT NULL REFERENCES household ON DELETE CASCADE,
    building_id   INT           NOT NULL REFERENCES building ON DELETE RESTRICT,
    note          VARCHAR(500),
    note_by       INT           REFERENCES buyer ON DELETE SET NULL,
    saved_by      INT           REFERENCES buyer ON DELETE SET NULL,
    saved_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    PRIMARY KEY (household_id, building_id)
);
COMMENT ON TABLE household_saved IS 'The shared shortlist. At most 50 per household (trigger c). note_by and saved_by become NULL if that account is deleted.';

-- Invitations a buyer has received, "who saved this block" across households, and the RESTRICT check
-- when a building is deleted.
CREATE INDEX household_invitation_invitee_idx ON household_invitation (invitee_id);
CREATE INDEX household_saved_building_idx ON household_saved (building_id);

-- (c) At most 50 blocks on a household's shortlist. As trigger (b) does for a buyer, locking the household
-- row first serialises concurrent saves by its two members, so both cannot see 49 and insert.
CREATE FUNCTION check_household_saved_cap() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    saved INT;
BEGIN
    PERFORM 1 FROM household WHERE household_id = NEW.household_id FOR UPDATE;
    SELECT count(*) INTO saved FROM household_saved WHERE household_id = NEW.household_id;
    IF saved >= 50 THEN
        RAISE EXCEPTION 'household % already has 50 saved blocks', NEW.household_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER household_saved_cap
BEFORE INSERT OR UPDATE OF household_id ON household_saved
FOR EACH ROW EXECUTE FUNCTION check_household_saved_cap();

-- (d) A household member saves to the household's shortlist, never to a personal one.
CREATE FUNCTION check_saved_building_owner() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM household_member WHERE buyer_id = NEW.buyer_id) THEN
        RAISE EXCEPTION 'buyer % is in a household, so saves go to its shortlist', NEW.buyer_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER saved_building_owner
BEFORE INSERT OR UPDATE OF buyer_id ON saved_building
FOR EACH ROW EXECUTE FUNCTION check_saved_building_owner();

GRANT INSERT, UPDATE, DELETE ON household, household_member, household_invitation, household_saved
    TO app_rw, app_admin;
GRANT USAGE ON SEQUENCE household_household_id_seq TO app_rw, app_admin;
